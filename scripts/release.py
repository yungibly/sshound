#!/usr/bin/env python3
"""Validate release inputs and generate metadata from smoke-tested archives."""
import argparse
import hashlib
from pathlib import Path
import re
import tomllib

ROOT = Path(__file__).resolve().parents[1]
CHANGELOG = ROOT / "CHANGELOG.md"
DESCRIPTION = "Play audio files from a remote shell and hear them on your own machine"
TARGETS = {
    "macos": {"arm": "aarch64-apple-darwin", "intel": "x86_64-apple-darwin"},
    "linux": {"arm": "aarch64-unknown-linux-musl", "intel": "x86_64-unknown-linux-musl"},
}

# The formula's own test: the version, and a listener that greets a player.
# `--null` discards the audio, so it runs on machines with no sound device.
FORMULA_TAIL = r'''
  def install
    bin.install "bin/sshound"
    doc.install "README.md", "BUILD.txt"
  end

  def caveats
    <<~EOS
      The player (`sshound FILE`) decodes with ffmpeg, which this formula does
      not install:
        brew install ffmpeg
      The listener (`sshound listen`) does not need it.
    EOS
  end

  test do
    assert_equal "sshound #{version}\n", shell_output("#{bin}/sshound --version")

    port = free_port
    pid = spawn bin/"sshound", "listen", "--null", "--bind", "127.0.0.1", "--port", port.to_s
    begin
      sleep 2
      TCPSocket.open("127.0.0.1", port) do |socket|
        socket.write "sshound2\x04brew"
        assert_equal "sshound2", socket.read(8)
      end
    ensure
      Process.kill("TERM", pid)
      Process.wait(pid)
    end
  end
end
'''


def validate_tag(tag, version):
    if not re.fullmatch(r"v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", tag):
        raise ValueError("release tags must have the form vMAJOR.MINOR.PATCH (no prereleases)")
    if tag != f"v{version}":
        raise ValueError(f"tag {tag!r} does not match Cargo.toml version {version!r}")


def release_notes(version, changelog=CHANGELOG):
    """The CHANGELOG section for this version, without its heading."""
    lines = changelog.read_text().splitlines()
    heading = re.compile(rf"## v{re.escape(version)}(?:\s|$)")
    starts = [i for i, line in enumerate(lines) if heading.match(line)]
    if len(starts) != 1:
        raise ValueError(f"{changelog.name} needs exactly one '## v{version}' section")
    body = []
    for line in lines[starts[0] + 1:]:
        if line.startswith("## "):
            break
        body.append(line)
    text = "\n".join(body).strip()
    if not text:
        raise ValueError(f"{changelog.name} section for v{version} is empty")
    return text


def prepare(tag, version, repository, packages, output, changelog=CHANGELOG):
    validate_tag(tag, version)
    notes = release_notes(version, changelog)
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repository):
        raise ValueError("repository must be OWNER/REPO")
    homepage = f"https://github.com/{repository}"
    digests = {}
    sums = []
    for targets in TARGETS.values():
        for target in targets.values():
            name = f"sshound-{version}-{target}.tar.gz"
            archive = packages / name
            # Recompute every checksum. Missing, renamed, or modified artifacts
            # must fail before either a release or a formula can be published.
            with archive.open("rb") as stream:
                digest = hashlib.file_digest(stream, "sha256").hexdigest()
            checksum = packages / f"{name}.sha256"
            expected = f"{digest}  {name}"
            if checksum.read_text().strip() != expected:
                raise ValueError(f"checksum mismatch: {name}")
            digests[target] = digest
            sums.append(expected)

    lines = [
        "# Generated by sshound's release workflow; see scripts/release.py.",
        "class Sshound < Formula",
        f'  desc "{DESCRIPTION}"',
        f'  homepage "{homepage}"',
        f'  version "{version}"',
    ]
    for system, targets in TARGETS.items():
        lines += ["", f"  on_{system} do"]
        if system == "macos":
            lines += ['    depends_on macos: :sonoma', ""]
        for arch, target in targets.items():
            name = f"sshound-{version}-{target}.tar.gz"
            lines += [
                f"    on_{arch} do",
                f'      url "{homepage}/releases/download/{tag}/{name}"',
                f'      sha256 "{digests[target]}"',
                "    end",
            ]
        lines += ["  end"]
    output.mkdir(parents=True, exist_ok=True)
    (output / "sshound.rb").write_text("\n".join(lines) + "\n" + FORMULA_TAIL)
    (output / "SHA256SUMS").write_text("\n".join(sums) + "\n")
    (output / "notes.md").write_text(
        notes + "\n\n"
        "## Install\n\n"
        "```sh\nbrew install yungibly/tap/sshound\n# Existing installation:\n"
        "brew update && brew upgrade sshound\n```\n\n"
        "Install it on both machines: the one with the audio files and the one "
        "you listen on. Native binaries for Apple Silicon and Intel macOS "
        "(Sonoma 14 or later), and ARM64 and x86-64 Linux (static musl). Each "
        "archive was built, tested, extracted, and smoke-tested on its matching "
        "architecture. To install by hand, download the matching `.tar.gz` and "
        "`SHA256SUMS`, verify with `shasum -a 256 --ignore-missing -c SHA256SUMS` "
        "on macOS or `sha256sum --ignore-missing -c SHA256SUMS` on Linux, then "
        "extract and copy `bin/sshound` onto your PATH.\n\n"
        "The player needs `ffmpeg` on the machine with the files. Automated "
        "checks cover the protocol and a silent listener on every platform; "
        "they cannot hear real audio output.\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["validate", "prepare"])
    parser.add_argument("--tag", required=True)
    parser.add_argument("--repository", default="yungibly/sshound")
    parser.add_argument("--packages", type=Path, default=ROOT / "target/packages")
    parser.add_argument("--output", type=Path, default=ROOT / "target/release-metadata")
    args = parser.parse_args()
    version = tomllib.loads((ROOT / "Cargo.toml").read_text())["package"]["version"]
    try:
        validate_tag(args.tag, version)
        release_notes(version)
        if args.command == "prepare":
            prepare(args.tag, version, args.repository, args.packages, args.output)
    except (ValueError, OSError) as error:
        parser.exit(1, f"release: {error}\n")
    print(f"Validated {args.tag}" + (f"; metadata: {args.output}" if args.command == "prepare" else ""))


if __name__ == "__main__":
    main()
